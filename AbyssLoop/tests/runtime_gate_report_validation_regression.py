"""Validate all eight runtime-report gates and reject stale/malformed evidence.

This is a contract test only. Fixtures are synthetic and never written to the
real project; this test does not execute Godot and is not runtime evidence.
"""
from __future__ import annotations
from pathlib import Path
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from package_release import validate_runtime_report  # noqa: E402
from release_integrity import project_fingerprint  # noqa: E402

REQUIRED_GATES = [
    "Static/regression suite",
    "Godot version",
    "Editor/import preflight",
    "Clean main-scene launch",
    "Gameplay smoke",
    "Save-system regression",
    "Expedition integration audit",
    "Inventory-to-settlement runtime acceptance",
]


def fixture_root(base: Path) -> Path:
    root = base / "AbyssLoop"
    (root / "tests" / "reports").mkdir(parents=True)
    (root / "project.godot").write_text('config/name="Abyss Loop"\nconfig/version="0.61.0"\n', encoding="utf-8")
    (root / "sentinel_source.gd").write_text("extends Node\n", encoding="utf-8")
    return root


def write_report(root: Path, *, result: str = "PASS", godot: str = "4.7.2.stable.official", build: str = "0.61.0", fingerprint: str | None = None, statuses: dict[str, str] | None = None, duplicate: str | None = None, extra: str | None = None) -> None:
    if fingerprint is None:
        fingerprint = project_fingerprint(root)
    if statuses is None:
        statuses = {label: "PASS" for label in REQUIRED_GATES}
    lines = [
        "# Synthetic report fixture — never used as runtime evidence",
        f"Result: {result}",
        f"Godot version: {godot}",
        f"Build version: {build}",
        f"Source fingerprint: {fingerprint}",
        "## Gates",
    ]
    lines.extend(f"- {label}: {status}" for label, status in statuses.items())
    if duplicate:
        lines.append(f"- {duplicate}: PASS")
    if extra:
        lines.append(extra)
    (root / "tests" / "reports" / "RUNTIME_GATE_REPORT_RU.md").write_text("\n".join(lines) + "\n", encoding="utf-8")


def expect_invalid(name: str, *, result: str = "PASS", godot: str = "4.7.2.stable.official", build: str = "0.61.0", fingerprint: str | None = None, statuses: dict[str, str] | None = None, duplicate: str | None = None, extra: str | None = None, expected_message: str) -> None:
    with tempfile.TemporaryDirectory(prefix="abyssloop_gate_report_") as temp:
        root = fixture_root(Path(temp))
        write_report(root, result=result, godot=godot, build=build, fingerprint=fingerprint, statuses=statuses, duplicate=duplicate, extra=extra)
        valid, message = validate_runtime_report(root)
        assert not valid, f"{name}: malformed report unexpectedly accepted"
        assert expected_message in message, f"{name}: expected '{expected_message}', got '{message}'"
        print(f"PASS: reject {name} ({message})")

with tempfile.TemporaryDirectory(prefix="abyssloop_gate_report_missing_") as temp:
    root = fixture_root(Path(temp))
    valid, message = validate_runtime_report(root)
    assert not valid and "missing" in message
    print("PASS: reject missing report")

expect_invalid("failed result", result="FAIL", expected_message="does not declare Result: PASS")
expect_invalid("non-exact result status", result="PASS (manual override)", expected_message="does not declare Result: PASS exactly once")
expect_invalid("duplicate result header", extra="Result: PASS", expected_message="does not declare Result: PASS exactly once")
expect_invalid("wrong engine version", godot="4.7.1.stable", expected_message="not generated by Godot 4.7.2")
expect_invalid("non-stable engine build", godot="4.7.2.rc1", expected_message="not generated by Godot 4.7.2")
expect_invalid("development engine build", godot="4.7.2.stable.dev", expected_message="not generated by Godot 4.7.2")
expect_invalid("wrong build version", build="0.55.0", expected_message="different build version")
expect_invalid("stale source fingerprint", fingerprint="0" * 64, expected_message="stale")

missing_statuses = {label: "PASS" for label in REQUIRED_GATES if label != "Godot version"}
expect_invalid("missing Godot version gate", statuses=missing_statuses, expected_message="incomplete")
failed_statuses = {label: "PASS" for label in REQUIRED_GATES}
failed_statuses["Gameplay smoke"] = "FAIL"
expect_invalid("one failed gate hidden behind Result PASS", statuses=failed_statuses, expected_message="non-PASS gates")
expect_invalid("duplicate gate row", duplicate="Gameplay smoke", expected_message="duplicate gate rows")
expect_invalid("unexpected gate row", extra="- unrecognized extra gate: PASS", expected_message="unexpected gate rows")

with tempfile.TemporaryDirectory(prefix="abyssloop_gate_report_valid_") as temp:
    root = fixture_root(Path(temp))
    write_report(root)
    valid, message = validate_runtime_report(root)
    assert valid, f"complete synthetic report contract should validate: {message}"
    print("PASS: accept complete report contract in isolated fixture")

print("RUNTIME GATE REPORT VALIDATION REGRESSION PASSED: 13 rejection cases and 1 isolated contract-acceptance case")
print("Synthetic report checks verify the validation contract only; no fixture is runtime evidence and no Godot process was run.")
